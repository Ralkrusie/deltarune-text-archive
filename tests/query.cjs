'use strict';
const assert=require('node:assert/strict'),Q=require('../web/query.js'),M=require('../web/model.js');
const query=(q,extra={})=>Q.compile({q,...extra});
assert(query('Susie').test('SUSIE'));assert(!query('Susie',{caseSensitive:true}).test('SUSIE'));
assert(query('cat',{wholeWord:true}).test('a cat!'));assert(!query('cat',{wholeWord:true}).test('cats'));
assert(!query('cat',{wholeWord:true}).test('cat_name'));assert(query('cat_name',{wholeWord:true}).test('cat_name'));
assert(!query('你好',{wholeWord:true}).test('你好世界'));assert(query('你好',{wholeWord:true}).test('你好！'));
assert(query('\\E3').test('text \\E3'));assert(query('[x]').test('[x]'));assert(!query('[x]').test('x'));
assert(query('^(YES|NO)$',{regex:true,caseSensitive:true}).test('YES'));assert(!query('^(YES|NO)$',{regex:true}).test('YES PLEASE'));
assert.deepEqual(query('^',{regex:true}).ranges('abc'),[]);assert(query('^',{regex:true}).test('abc'));
assert.deepEqual(query('Susie',{wholeWord:true}).ranges('Susies, Susie!'),[[8,13]]);
assert.throws(()=>query('[',{regex:true}),/正则表达式有误/);
assert.throws(()=>query('x'.repeat(257),{regex:true}),/256/);
const state=M.stateFrom(new URLSearchParams('q=YES&case=1&word=1&regex=1&highlight=0'));
assert.deepEqual(M.stateFrom(M.paramsFor(state)),state);
console.log('Search options checked: case, Unicode word boundaries, literal escaping, regex/empty matches, validation, highlights, URL state.');
