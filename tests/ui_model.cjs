'use strict';
const assert=require('node:assert/strict'),M=require('../web/model.js');
const row={zh_default:'甲',zh_names:'乙',zh_recruitable:'甲'};
assert.deepEqual(M.chineseRows(row,'smart').map(g=>[g.raw,g.fields.length]),[['甲',2],['乙',1]]);
assert.equal(M.chineseRows({zh_default:'甲',zh_recruitable:null,zh_names:''},'recruitable')[0].raw,null);
assert.equal(M.chineseRows({zh_default:'甲',zh_recruitable:null,zh_names:''},'smart').length,3);
assert.equal(M.chineseRows({zh_default:'甲',zh_recruitable:'甲',zh_names:'甲'},'smart').length,1);
assert.equal(M.chineseRows({zh_default:'\\E1甲',zh_recruitable:'甲',zh_names:'甲'},'smart').length,2);
const state=M.stateFrom(new URLSearchParams('ch=4&lang=en,zh&mode=source&layout=vertical&zh=names&q=hello&page=2'));
assert.deepEqual(M.stateFrom(M.paramsFor(state)),state);
const restore=M.stateFrom(new URLSearchParams('mode=restore&q=Kris&ch=1,3'));
assert.equal(restore.mode,'restore');assert.deepEqual(M.stateFrom(M.paramsFor(restore)),restore);
assert.deepEqual(M.fieldsFor(state),['en','zh_names']);
assert.deepEqual(M.stateFrom(new URLSearchParams('ch=99&lang=bad&mode=bad&page=-1')).ch,[1,2,3,4,5]);
assert.deepEqual(state.ch,[4]);
const multiple=M.stateFrom(new URLSearchParams('ch=3,1,3,99'));
assert.deepEqual(multiple.ch,[1,3]);
assert.equal(M.paramsFor(multiple).get('ch'),'1,3');
assert.deepEqual(M.stateFrom(M.paramsFor(multiple)),multiple);
assert.equal(M.paramsFor({...state,ch:0}).get('ch'),'0');
assert.deepEqual(M.toggleChapter(0,1),[1]);
assert.deepEqual(M.toggleChapter([1],3),[1,3]);
assert.deepEqual(M.toggleChapter([1,3],1),[3]);
assert.deepEqual(M.toggleChapter([3],3),[3]);
assert.deepEqual(M.toggleChapter([3],0),[1,2,3,4,5]);
assert.equal(M.stateFrom(new URLSearchParams('ch=99&lang=bad&mode=bad&page=-1')).page,1);
assert.deepEqual(M.stateFrom(new URLSearchParams('lang=bad')).lang,['en','ja','zh']);
assert.equal(M.stateFrom(new URLSearchParams(),{},true).layout,'vertical');
assert.equal(M.stateFrom(new URLSearchParams('layout=horizontal'),{},true).layout,'horizontal');
